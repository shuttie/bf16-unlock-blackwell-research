#!/usr/bin/env python3
"""
Generate a self-signed COT key/signature pair for the FMC key-anchor test.

Produces (next to this script):
  bf16_cot_key.pem   private key (secp384r1)
  bf16_cot_pub.der   SPKI public key
  bf16_cot_pub.bin   raw uncompressed point (97 B: 04 || X || Y)
  bf16_cot_sig.bin   raw signature (96 B: r || s) over the supplied hash
  bf16_cot_key.h     C header with the two byte arrays

The signature is ECDSA P-384 over the 48-byte SHA-384 digest, matching the
production encoding verified against c04_hash.bin / c04_pkey.bin / c04_sig.bin.
"""
import argparse
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent

SPKI_PREFIX = bytes.fromhex("3076301006072a8648ce3d020106052b81040022036200")


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"command failed: {' '.join(cmd)}\n{r.stdout}{r.stderr}")
    return r.stdout


def der_integer(b):
    b = b.lstrip(b"\x00") or b"\x00"
    if b[0] & 0x80:
        b = b"\x00" + b
    return b"\x02" + bytes([len(b)]) + b


def raw_to_der_sig(raw):
    if len(raw) != 96:
        sys.exit(f"raw signature is {len(raw)} bytes, expected 96")
    body = der_integer(raw[:48]) + der_integer(raw[48:])
    return b"\x30" + bytes([len(body)]) + body


def der_to_raw_sig(der):
    if der[0] != 0x30:
        sys.exit("signature is not a DER SEQUENCE")
    p = 2
    out = []
    for _ in range(2):
        if der[p] != 0x02:
            sys.exit("expected DER INTEGER")
        ln = der[p + 1]
        val = der[p + 2:p + 2 + ln]
        p += 2 + ln
        val = val.lstrip(b"\x00")
        if len(val) > 48:
            sys.exit("DER integer longer than 48 bytes")
        out.append(val.rjust(48, b"\x00"))
    return b"".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hash", default="c04_hash.bin",
                    help="48-byte SHA-384 digest to sign")
    ap.add_argument("--key", default=str(HERE / "bf16_cot_key.pem"),
                    help="private key to use (created if missing)")
    ap.add_argument("--force-key", action="store_true", help="regenerate the private key")
    ap.add_argument("--header", default=str(HERE / "bf16_cot_key.h"))
    args = ap.parse_args()

    key = pathlib.Path(args.key)
    digest = pathlib.Path(args.hash).read_bytes()
    if len(digest) != 48:
        sys.exit(f"hash is {len(digest)} bytes, expected 48")

    if args.force_key or not key.exists():
        run(["openssl", "ecparam", "-name", "secp384r1", "-genkey", "-noout",
             "-out", str(key)])
        print(f"generated {key}")

    pub_der = HERE / "bf16_cot_pub.der"
    run(["openssl", "ec", "-in", str(key), "-pubout", "-conv_form", "uncompressed",
         "-outform", "DER", "-out", str(pub_der)])
    pub_raw = pub_der.read_bytes()[-97:]
    if pub_raw[0] != 0x04:
        sys.exit("public key is not an uncompressed point")
    (HERE / "bf16_cot_pub.bin").write_bytes(pub_raw)
    run(["openssl", "pkey", "-pubin", "-inform", "DER", "-in", str(pub_der),
         "-out", str(HERE / "bf16_cot_pub.pem")])

    sig_der = HERE / "bf16_cot_sig.der"
    run(["openssl", "pkeyutl", "-sign", "-inkey", str(key), "-in", args.hash,
         "-pkeyopt", "digest:sha384", "-out", str(sig_der)])
    raw_sig = der_to_raw_sig(sig_der.read_bytes())
    (HERE / "bf16_cot_sig.bin").write_bytes(raw_sig)

    # Re-encode and verify exactly the bytes we will put in the COT.
    check_der = HERE / "bf16_cot_sig.check.der"
    check_der.write_bytes(raw_to_der_sig(raw_sig))
    out = run(["openssl", "pkeyutl", "-verify", "-pubin", "-inkey",
               str(HERE / "bf16_cot_pub.pem"), "-in", args.hash,
               "-sigfile", str(check_der), "-pkeyopt", "digest:sha384"])
    print(f"self-verify: {out.strip()}")

    def carray(name, data):
        lines = [f"static const NvU8 {name}[{len(data)}] = {{"]
        for i in range(0, len(data), 12):
            chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
            lines.append(f"    {chunk},")
        lines.append("};")
        return "\n".join(lines)

    header = (
        "/* Auto-generated by driver-harness/gen_cot_key.py — do not edit. */\n"
        "#pragma once\n"
        f"/* ECDSA P-384 over these 48 digest bytes: {digest.hex()} */\n"
        + carray("bf16_cot_pubkey", pub_raw) + "\n\n"
        + carray("bf16_cot_sig", raw_sig) + "\n"
    )
    pathlib.Path(args.header).write_text(header)
    print(f"wrote {args.header} ({len(pub_raw)}B key, {len(raw_sig)}B sig)")
    print(f"key first bytes: {pub_raw[:8].hex()}")
    print(f"sig first bytes: {raw_sig[:8].hex()}")


if __name__ == "__main__":
    main()
